#!/usr/bin/env bash
# World persistence differential test (stage M2): the REAL vanilla server generates a world, then
#   1. vanilla and the Rust server both load a copy of that world and the chunk packets they send are compared
#      (tools/world_compare.py: heightmaps, block entities, section data, ...),
#   2. the Rust server breaks a block, saves the world on shutdown (SIGTERM), and the vanilla server loads the
#      Rust-saved world: exactly the edited block may differ.
#
# REQUIRES acceptance of the Mojang EULA (https://aka.ms/MinecraftEULA). The script writes eula=true into its working
# directory ONLY when you set MC_EULA_ACCEPTED=true, i.e. you knowingly confirm that you accept the EULA.
#   MC_EULA_ACCEPTED=true tools/world_compare.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
if [ "${MC_EULA_ACCEPTED:-}" != "true" ]; then
  echo "This test runs the vanilla server, which requires accepting the Mojang EULA." >&2
  echo "Read https://aka.ms/MinecraftEULA and, if you agree, run: MC_EULA_ACCEPTED=true $0" >&2
  exit 2
fi
[ -f reference/dl/server.jar ] || tools/fetch_reference.sh
cargo build -q --release -p mc-server -p mc-probe
P="$ROOT/target/release/mc-probe"
W="$ROOT/reference/world-compare"
# REUSE_GEN=1 keeps the world generated by an earlier run (generation takes about a minute)
if [ "${REUSE_GEN:-}" = 1 ] && [ -d "$W/gen/world/region" ]; then
  rm -rf "$W/vanilla" "$W/rust" "$W/after" "$W/after_rust" "$W/dumps" "$W"/compare*.txt; REGEN=0
else
  rm -rf "$W"; REGEN=1
fi
mkdir -p "$W/gen" "$W/vanilla" "$W/rust" "$W/after" "$W/after_rust" "$W/dumps"
GEN_SECS="${GEN_SECS:-60}"

props() { # port
  printf '%s\n' "online-mode=false" "level-seed=12345" "view-distance=6" "simulation-distance=6" "gamemode=creative" \
    "difficulty=easy" "spawn-protection=0" "enforce-secure-profile=false" "server-port=$1"
}
PIDS=()
cleanup() { kill "${PIDS[@]}" 2>/dev/null || true; }
trap cleanup EXIT

start_vanilla() { # dir port  (sets VPID)
  echo "eula=true" > "$1/eula.txt"; props "$2" > "$1/server.properties"
  (cd "$1" && exec java -Xmx1G -jar "$ROOT/reference/dl/server.jar" nogui >server.out 2>&1 </dev/null) & VPID=$!; PIDS+=($VPID)
  for _ in $(seq 1 240); do grep -q 'Done (' "$1/server.out" 2>/dev/null && return 0; sleep 0.5; done
  echo "The vanilla server did not start (port $2 in use / world lock?). Last lines:" >&2; tail -5 "$1/server.out" >&2; exit 3
}
start_rust() { # dir port  (sets RPID)
  props "$2" > "$1/server.properties"
  "$ROOT/target/release/mc-server" --dir "$1" >"$1/server.log" 2>&1 & RPID=$!; PIDS+=($RPID)
  for _ in $(seq 1 80); do (echo > "/dev/tcp/127.0.0.1/$2") 2>/dev/null && return 0; sleep 0.25; done
  echo "The Rust server did not start" >&2; tail -5 "$1/server.log" >&2; exit 3
}
stop() { kill -TERM "$1" 2>/dev/null || true; wait "$1" 2>/dev/null || true; }

if [ "$REGEN" = 1 ]; then
  echo "### 1/4 the vanilla server generates and saves a world (${GEN_SECS}s)"
  start_vanilla "$W/gen" 25572; V=$VPID
  "$P" join --port 25572 --name Explorer --secs "$GEN_SECS" >/dev/null 2>&1 || true
  stop "$V"
else
  echo "### 1/4 reusing the world generated earlier"
fi
[ -d "$W/gen/world/region" ] || { echo "no world was generated" >&2; exit 3; }
for d in vanilla rust; do cp -r "$W/gen/world" "$W/$d/world"; rm -f "$W/$d/world/session.lock"; done

echo "### 2/4 vanilla and Rust load the same stored world"
start_vanilla "$W/vanilla" 25572; V=$VPID
"$P" join --port 25572 --name Explorer --secs 10 --dump "$W/dumps/vanilla.bin" >/dev/null 2>&1 || true
stop "$V"
start_rust "$W/rust" 25573; R=$RPID
# (the probe's own flat-world checks fail on a real world, hence "|| true")
POS=$({ "$P" join --port 25573 --name Explorer --secs 10 --dump "$W/dumps/rust.bin" 2>&1 || true; } | sed -n 's/.*POSITION (\([^)]*\)).*/\1/p' | head -1)
stop "$R"
FAIL=0
python3 -I tools/world_compare.py "$W/dumps/vanilla.bin" "$W/dumps/rust.bin" > "$W/compare1.txt" || FAIL=1
cat "$W/compare1.txt"

echo "### 3/4 the Rust server breaks the block under the player and saves on SIGTERM"
cp -r "$W/gen/world" "$W/after/world"; rm -f "$W/after/world/session.lock"
start_rust "$W/after" 25573; R=$RPID
"$P" join --port 25573 --name Explorer --secs 6 --break below >/dev/null 2>&1 || true
stop "$R"
grep -E "World saved" "$W/after/server.log" || { echo "the Rust server did not save the world" >&2; exit 4; }
# the same saved world for the last step, before vanilla opens (and re-saves) it
cp -r "$W/after/world" "$W/after_rust/world"; rm -f "$W/after_rust/world/session.lock"
EDIT=$(python3 -I -c "
import math,sys
x,y,z=[float(v) for v in '$POS'.split(',')]
print('%d,%d,%d' % (math.floor(x), math.floor(y) - 1, math.floor(z)))")

echo "### 4/4 the vanilla server loads the world saved by the Rust server (edited block: $EDIT)"
start_vanilla "$W/after" 25572; V=$VPID
"$P" join --port 25572 --name Explorer --secs 10 --dump "$W/dumps/after.bin" >/dev/null 2>&1 || true
stop "$V"
if grep -E "ERROR|Failed to|corrupt|Exception" "$W/after/server.out" | grep -v "Server thread/WARN"; then
  echo "The vanilla server reported problems while loading the Rust-saved world" >&2; exit 5
fi

echo "### 5/5 the Rust server serves the world it saved itself (the edited chunk has no stored light): compared with vanilla"
start_rust "$W/after_rust" 25573; R=$RPID
{ "$P" join --port 25573 --name Explorer --secs 10 --dump "$W/dumps/after_rust.bin" >/dev/null 2>&1 || true; }
stop "$R"
python3 -I tools/world_compare.py "$W/dumps/vanilla.bin" "$W/dumps/rust.bin" --after "$W/dumps/after.bin" "$EDIT" --after-rust "$W/dumps/after_rust.bin" > "$W/compare2.txt" || FAIL=1
sed -n '/^edit check\|^saved world/p' "$W/compare2.txt"
if [ "$FAIL" = 0 ]; then echo "### OK: world persistence verified against the vanilla server"; else echo "### FAILED (see $W/compare*.txt)" >&2; fi
exit "$FAIL"
